import { pickUniqueSheetName, sourceNoteText, uniquifyOutputSheets } from './output-sheet.util';
import { SheetActionPayload } from '../types/sheet-actions.types';

const make = (name: string): SheetActionPayload[] => [
  { type: 'CREATE_SHEET', sheetName: name, name, relativeTo: 'Books', position: 'after', uniqueName: true },
  { type: 'WRITE_TABLE', sheetName: name, headers: ['A'], rows: [['x']] },
  { type: 'FREEZE_PANES', sheetName: name, freezeRows: 1 },
];

describe('P1.2 output sheet writer', () => {
  it('keeps the name when free', () => {
    expect(pickUniqueSheetName('Recon', ['Books'])).toBe('Recon');
  });

  it('adds (2), (3) on collisions, case-insensitively', () => {
    expect(pickUniqueSheetName('Recon', ['recon'])).toBe('Recon (2)');
    expect(pickUniqueSheetName('Recon', ['Recon', 'Recon (2)'])).toBe('Recon (3)');
  });

  it('never exceeds 31 characters', () => {
    const long = 'Recon 3B-vs-2B April 2026 final x';
    const r = pickUniqueSheetName(long, [long.slice(0, 31)]);
    expect(r.length).toBeLessThanOrEqual(31);
    expect(r.endsWith('(2)')).toBe(true);
  });

  it('second run is renamed and every action for it follows; relativeTo untouched', () => {
    const out = uniquifyOutputSheets(make('Recon'), ['Books', 'Recon']);
    expect(out[0]).toMatchObject({ type: 'CREATE_SHEET', name: 'Recon (2)', sheetName: 'Recon (2)', relativeTo: 'Books' });
    expect(out[0].uniqueName).toBeUndefined();
    expect(out[1].sheetName).toBe('Recon (2)');
    expect(out[2].sheetName).toBe('Recon (2)');
  });

  it('keeps the name when it is free', () => {
    const out = uniquifyOutputSheets(make('Recon'), ['Books']);
    expect(out.map((a) => a.sheetName)).toEqual(['Recon', 'Recon', 'Recon']);
  });

  it('two same-named creations in one batch do not collide with each other', () => {
    const out = uniquifyOutputSheets([...make('Recon'), ...make('Recon')], ['Books']);
    const creates = out.filter((a) => a.type === 'CREATE_SHEET').map((a) => a.name);
    expect(new Set(creates).size).toBe(2);
  });

  it('leaves non-output sheet creation alone (old reuse behaviour)', () => {
    const actions: SheetActionPayload[] = [{ type: 'CREATE_SHEET', sheetName: 'Recon', name: 'Recon' }];
    expect(uniquifyOutputSheets(actions, ['Recon'])).toBe(actions);
  });

  it('source note names sheet and date', () => {
    expect(sourceNoteText('Purchase Register', new Date(2026, 10, 5))).toBe(
      'Generated by CELLIX from Purchase Register on 05-Nov-2026',
    );
    expect(sourceNoteText(undefined, new Date(2026, 0, 9))).toBe('Generated by CELLIX on 09-Jan-2026');
  });
});
